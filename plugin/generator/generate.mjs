#!/usr/bin/env node
// Turns a project's devkit.json into every kit-owned file. Nothing else writes a kit-owned file.
// See README.md beside this file.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { CONFIG_FILE, DevkitConfigError, checkDevkitConfig, parseDevkitConfig } from '../devkit-config.mjs';

export const ACTION = 'josephmitchel/jm-devkit/reviewer@main';
export const SWEEP_WORKFLOW = '.github/workflows/nightly-sweep.yml';

/** Every kit-owned file for `config`, as `{ path: contents }` with paths relative to the project root. */
export function generate(config) {
  checkDevkitConfig(config);
  return { [SWEEP_WORKFLOW]: sweepWorkflow(config) };
}

const HEADER = `# Generated by the devkit generator (plugin/generator/generate.mjs in josephmitchel/jm-devkit)
# from this project's devkit.json. Do not edit it by hand: change devkit.json, then sync.
`;

const SECRETS = `          database-url: \${{ secrets.DATABASE_URL }}
          claude-code-oauth-token: \${{ secrets.CLAUDE_CODE_OAUTH_TOKEN }}
          app-client-id: \${{ secrets.REVIEWER_APP_CLIENT_ID }}
          app-private-key: \${{ secrets.REVIEWER_APP_PRIVATE_KEY }}
`;

function sweepWorkflow(config) {
  const services = testServices(config.reviewer.services);
  return `${HEADER}#
# The nightly sweep replaces per-PR review with an advisory backlog. Every night it:
#   1. applies your decisions: a ticket labelled \`wontfix\` is closed as not planned, its blocking
#      edges lifted, and the comment you gave with the label saved as a repo policy; a reviewer
#      issue you closed by hand is final and never judged;
#   2. reads your replies on issues labelled \`needs-answer\` and saves them as policy;
#   3. audits what landed on the default branch since the last sweep (ISO/IEC 25010, ten auditors)
#      and files each major or moderate concern as an issue, minors into one digest issue;
#   4. judges every ticket labelled \`needs-judging\` — the reviewer's own issues included — against
#      its text and the repo's standards: closed as completed, or \`needs-work\` with a brief;
# It never pushes a fix and never sets a commit status, so nothing blocks a merge.
#
# The \`landed\` job runs when a PR merges: every ticket the PR body names with \`Addresses #N\` is
# labelled \`needs-judging\` for that night's judge, and the tickets it blocked are unblocked (the
# "blocked by" edge becomes "relates to"), so dependent work can start the same day.
#
# The \`review-now\` job is the escape hatch: put the \`review-now\` label on a PR to get the full
# per-PR review (questions, fixes, gate) on demand.
name: Code Reviewer sweep

on:
  # The schedule lives in the code reviewer's Cloudflare Worker, which dispatches this workflow
  # on the minute; GitHub's own \`schedule\` runs hours late.
  workflow_dispatch:
  pull_request:
    types: [labeled, closed]

permissions: {}

jobs:
  sweep:
    if: github.event_name == 'schedule' || github.event_name == 'workflow_dispatch'
    # One sweep at a time per repo. A second run while one is still going waits for it.
    concurrency:
      group: code-reviewer-sweep-\${{ github.repository }}
      cancel-in-progress: false
    runs-on: ubuntu-latest
    timeout-minutes: 330
${services}    steps:
      - uses: ${ACTION}
        with:
          command: sweep
${SECRETS}
  landed:
    if: github.event_name == 'pull_request' && github.event.action == 'closed' && github.event.pull_request.merged == true
    runs-on: ubuntu-latest
    timeout-minutes: 10
    steps:
      - uses: ${ACTION}
        with:
          command: landed
          pr: \${{ github.event.pull_request.number }}
${SECRETS}
  review-now:
    if: >-
      github.event_name == 'pull_request' && github.event.action == 'labeled' &&
      github.event.label.name == 'review-now' && github.event.pull_request.draft == false
    concurrency:
      group: code-reviewer-\${{ github.repository }}
      cancel-in-progress: false
    runs-on: ubuntu-latest
    timeout-minutes: 330
${services}    steps:
      - uses: ${ACTION}
        with:
          pr: \${{ github.event.pull_request.number }}
${SECRETS}`;
}

// The order GitHub's docs give a service's fields in. Service ids and env names are sorted, so
// reordering devkit.json never changes the output.
const SERVICE_FIELDS = ['image', 'credentials', 'env', 'ports', 'volumes', 'options'];

function testServices(services) {
  const ids = Object.keys(services ?? {}).sort();
  if (ids.length === 0) return `    # A service the tests need, a database say, goes in devkit.json as reviewer.services.\n`;
  const lines = ['    # The services the tests need, from devkit.json\'s reviewer.services.', '    services:'];
  for (const id of ids) {
    lines.push(`      ${scalar(id)}:`);
    const service = services[id];
    for (const field of SERVICE_FIELDS) {
      if (service[field] !== undefined) lines.push(...yaml(field, service[field], 8));
    }
  }
  return `${lines.join('\n')}\n`;
}

function yaml(key, value, indent) {
  const pad = ' '.repeat(indent);
  if (Array.isArray(value)) {
    if (value.length === 0) return [`${pad}${scalar(key)}: []`];
    return [`${pad}${scalar(key)}:`, ...value.map((item) => `${pad}  - ${scalar(item)}`)];
  }
  if (typeof value === 'object' && value !== null) {
    const keys = key === 'credentials' ? ['username', 'password'] : Object.keys(value).sort();
    if (keys.length === 0) return [`${pad}${scalar(key)}: {}`];
    return [`${pad}${scalar(key)}:`, ...keys.flatMap((k) => yaml(k, value[k], indent + 2))];
  }
  return [`${pad}${scalar(key)}: ${scalar(value)}`];
}

const YAML_WORDS = /^(y|n|yes|no|on|off|true|false|null|~)$/i;

/** A YAML scalar that reads back as exactly `value`, plain where that is unambiguous. */
function scalar(value) {
  if (typeof value === 'number') return String(value);
  if (/^[A-Za-z_/][A-Za-z0-9_./:@+=-]*$/.test(value) && !YAML_WORDS.test(value)) return value;
  if (!/[\u0000-\u001f\u007f]/.test(value)) return `'${value.replaceAll("'", "''")}'`;
  return JSON.stringify(value);
}

/** Read and validate `<projectDir>/devkit.json`. */
export function readConfig(projectDir) {
  const file = path.join(projectDir, CONFIG_FILE);
  if (!fs.existsSync(file)) throw new DevkitConfigError(`no ${CONFIG_FILE} in ${projectDir}`);
  return parseDevkitConfig(fs.readFileSync(file, 'utf8'));
}

/** The kit-owned files under `projectDir` that are missing or differ from `files`. */
export function drifted(projectDir, files) {
  return Object.entries(files)
    .filter(([relative, contents]) => {
      const file = path.join(projectDir, relative);
      return !fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== contents;
    })
    .map(([relative]) => relative);
}

const USAGE = 'usage: node generate.mjs <projectDir> [--check]';

/** The CLI. Returns the exit code: 0 done or level, 1 behind (with --check), 2 could not generate. */
export function main(argv, out = process.stdout, err = process.stderr) {
  const check = argv.includes('--check');
  const rest = argv.filter((a) => a !== '--check');
  if (rest.length !== 1 || rest[0].startsWith('-')) {
    err.write(`${USAGE}\n`);
    return 2;
  }
  const projectDir = rest[0];

  let files;
  try {
    files = generate(readConfig(projectDir));
  } catch (e) {
    if (!(e instanceof DevkitConfigError)) throw e;
    if (e.errors.length === 0) err.write(`${e.message}\n`);
    else err.write(`${CONFIG_FILE} is malformed:\n${e.errors.map((m) => `  ${m}\n`).join('')}`);
    return 2;
  }

  const behind = drifted(projectDir, files);
  if (check) {
    for (const relative of behind) out.write(`${relative}\n`);
    if (behind.length > 0) err.write(`${behind.length} kit-owned file(s) differ from what ${CONFIG_FILE} generates\n`);
    return behind.length > 0 ? 1 : 0;
  }
  for (const relative of behind) {
    const file = path.join(projectDir, relative);
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, files[relative]);
    out.write(`wrote ${relative}\n`);
  }
  return 0;
}

if (process.argv[1] && fs.realpathSync(process.argv[1]) === fileURLToPath(import.meta.url)) {
  process.exitCode = main(process.argv.slice(2));
}
