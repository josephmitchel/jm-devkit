// The sweep workflow is retired, but a project that has not moved still runs its copy. These pin
// what that copy is.

import { test } from 'node:test';
import assert from 'node:assert/strict';

import { ACTION, lastSweepWorkflow } from './retired-sweep-workflow.mjs';

const minimal = {
  modules: ['process'],
  sweep: { hour: 3 },
  reviewer: { tests: [{ name: 'unit', command: 'npm test' }] },
};

const withDatabase = {
  modules: ['process'],
  sweep: { hour: 5 },
  reviewer: {
    setup: 'npm ci',
    tests: [
      { name: 'unit', command: 'npm test' },
      { name: 'db', command: 'npm run test:db' },
    ],
    env: { TEST_DATABASE_URL: 'postgresql://postgres:postgres@localhost:5432/app_test' },
    services: {
      postgres: {
        image: 'postgres:16',
        env: { POSTGRES_USER: 'postgres', POSTGRES_PASSWORD: 'postgres' },
        ports: ['5432:5432'],
        options: '--health-cmd pg_isready --health-interval 10s --health-timeout 5s --health-retries 5',
      },
    },
  },
};

const servicesBlock = `    services:
      postgres:
        image: postgres:16
        env:
          POSTGRES_PASSWORD: postgres
          POSTGRES_USER: postgres
        ports:
          - '5432:5432'
        options: '--health-cmd pg_isready --health-interval 10s --health-timeout 5s --health-retries 5'
`;

/** The text of each job in the workflow, by job id. */
function jobs(workflow) {
  const body = workflow.slice(workflow.indexOf('\njobs:\n') + '\njobs:\n'.length);
  const parts = body.split(/^ {2}(?=[a-z-]+:\n)/m).filter(Boolean);
  return Object.fromEntries(parts.map((part) => [part.slice(0, part.indexOf(':')), part]));
}

test('a minimal config gave the three jobs on the action, under a header saying it was generated', () => {
  const workflow = lastSweepWorkflow(minimal);
  const [first, second] = workflow.split('\n');
  assert.match(first, /^# Generated by the devkit generator/);
  assert.match(second, /change devkit\.json/);
  assert.deepEqual(Object.keys(jobs(workflow)), ['sweep', 'landed', 'review-now']);
  assert.equal(workflow.split(`- uses: ${ACTION}\n`).length - 1, 3);
  assert.doesNotMatch(workflow, /^\s+services:/m);
  assert.doesNotMatch(workflow, /repo-env|schedule:|Copy this into/);
  assert.ok(workflow.endsWith('}}\n') && !workflow.endsWith('\n\n'));
});

test('a test database service went on the jobs that run the tests, and its env stayed in devkit.json', () => {
  const byJob = jobs(lastSweepWorkflow(withDatabase));
  assert.ok(byJob.sweep.includes(servicesBlock), byJob.sweep);
  assert.ok(byJob['review-now'].includes(servicesBlock), byJob['review-now']);
  assert.doesNotMatch(byJob.landed, /services:/);
  for (const job of Object.values(byJob)) assert.doesNotMatch(job, /repo-env|TEST_DATABASE_URL/);
});

test('a service value YAML would misread was quoted', () => {
  const config = structuredClone(withDatabase);
  config.reviewer.services.postgres.env = { ON: 'yes', POSTGRES_PASSWORD: "it's ${{ secrets.PG }}" };
  config.reviewer.services.postgres.ports = [5432];
  const workflow = lastSweepWorkflow(config);
  assert.match(workflow, /^ {10}'ON': 'yes'$/m);
  assert.match(workflow, /^ {10}POSTGRES_PASSWORD: 'it''s \$\{\{ secrets\.PG \}\}'$/m);
  assert.match(workflow, /^ {10}- 5432$/m);
});

test('only reviewer.services varied it: not the sweep hour, the databases or the nightly checks', () => {
  const { sweep, ...noSweep } = withDatabase;
  const more = {
    ...withDatabase,
    reviewer: { ...withDatabase.reviewer, databases: ['TEST_DATABASE_URL'] },
    nightly: { checks: [{ name: 'canvas', command: 'npm run canvas:check' }] },
  };
  assert.equal(lastSweepWorkflow(noSweep), lastSweepWorkflow(withDatabase));
  assert.equal(lastSweepWorkflow(more), lastSweepWorkflow(withDatabase));
  assert.notEqual(lastSweepWorkflow(minimal), lastSweepWorkflow(withDatabase));
});

test('the order devkit.json listed things in changed nothing', () => {
  const reordered = structuredClone(withDatabase);
  const postgres = reordered.reviewer.services.postgres;
  reordered.reviewer.services = {
    postgres: { options: postgres.options, ports: postgres.ports, image: postgres.image, env: { POSTGRES_PASSWORD: 'postgres', POSTGRES_USER: 'postgres' } },
  };
  assert.equal(lastSweepWorkflow(reordered), lastSweepWorkflow(withDatabase));
});
