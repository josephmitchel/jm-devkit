import { after, test } from 'node:test';
import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { DevkitConfigError } from '../devkit-config.mjs';
import { SWEEP_WORKFLOW, generate } from './generate.mjs';

const script = fileURLToPath(new URL('./generate.mjs', import.meta.url));
const kitRoot = fileURLToPath(new URL('../../', import.meta.url));

const minimal = {
  modules: ['process'],
  reviewer: { tests: [{ name: 'unit', command: 'npm test' }] },
};

const withDatabase = {
  modules: ['process'],
  reviewer: {
    setup: 'npm ci',
    tests: [
      { name: 'unit', command: 'npm test' },
      { name: 'db', command: 'npm run test:db' },
    ],
    databases: ['TEST_DATABASE_URL'],
  },
};

const dirs = [];
after(() => dirs.forEach((dir) => fs.rmSync(dir, { recursive: true, force: true })));

function project(config) {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'devkit-generate-'));
  dirs.push(dir);
  if (config !== undefined) fs.writeFileSync(path.join(dir, 'devkit.json'), JSON.stringify(config, null, 2));
  return dir;
}

function cli(...args) {
  const run = spawnSync(process.execPath, [script, ...args], { encoding: 'utf8' });
  return { code: run.status, stdout: run.stdout, stderr: run.stderr };
}

function generateError(config) {
  try {
    generate(config);
  } catch (err) {
    assert.ok(err instanceof DevkitConfigError);
    return err.errors;
  }
  assert.fail('expected generate to refuse this config');
}

test('a valid config gives no file for the sweep workflow: the kit no longer writes it', () => {
  assert.deepEqual(generate(minimal), {});
  assert.deepEqual(generate(withDatabase), {});
  assert.equal(SWEEP_WORKFLOW, '.github/workflows/nightly-sweep.yml');
});

test('an unknown field is refused, naming it', () => {
  const config = { ...minimal, reviewer: { ...minimal.reviewer, servics: {} } };
  assert.deepEqual(generateError(config), ['reviewer.servics is not a known field']);
});

test('a deploy section gives the project no kit-owned file, and one missing a field is refused', () => {
  const deploy = { setup: 'npm ci', build: 'npm run build', start: 'npm start', port: 3000, healthPath: '/healthz' };
  assert.deepEqual(generate({ ...minimal, deploy }), generate(minimal));
  const { port, ...noPort } = deploy;
  assert.deepEqual(generateError({ ...minimal, deploy: noPort }), ['deploy.port is required']);
});

test('a missing field is refused, naming it', () => {
  const { reviewer, ...config } = minimal;
  assert.deepEqual(generateError(config), ['reviewer is required']);
});


test("the kit's own devkit.json generates", () => {
  const config = JSON.parse(fs.readFileSync(path.join(kitRoot, 'devkit.json'), 'utf8'));
  assert.deepEqual(generate(config), {});
});

/** A project that has not moved: its config, and the sweep workflow as some earlier kit wrote it. */
function onActions(config = minimal, workflow = '# Generated by the devkit generator\nname: Code Reviewer sweep\n') {
  const dir = project(config);
  const file = path.join(dir, SWEEP_WORKFLOW);
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, workflow);
  return { dir, file, workflow };
}

test('--check exits 0 on a project with no sweep workflow, and writes nothing', () => {
  const dir = project(withDatabase);
  const run = cli(dir, '--check');
  assert.deepEqual(run, { code: 0, stdout: '', stderr: '' });
  assert.deepEqual(fs.readdirSync(dir), ['devkit.json']);
});

test('--check lists a project that still has the sweep workflow as behind, says why, and leaves it there', () => {
  const { dir, file, workflow } = onActions();
  const run = cli(dir, '--check');
  assert.equal(run.code, 1);
  assert.equal(run.stdout, `${SWEEP_WORKFLOW}\n`);
  assert.match(run.stderr, /^\.github\/workflows\/nightly-sweep\.yml is retired: removing it lets the code reviewer on the development machine handle the project, which it leaves alone while the file is there$/m);
  assert.equal(fs.readFileSync(file, 'utf8'), workflow);
});

test('writing removes the sweep workflow, hand-edited or not, and the project is then level', () => {
  for (const workflow of [undefined, 'name: a hand edit\n']) {
    const { dir, file } = workflow === undefined ? onActions() : onActions(withDatabase, workflow);
    const config = fs.readFileSync(path.join(dir, 'devkit.json'), 'utf8');

    assert.deepEqual(cli(dir), { code: 0, stdout: `removed ${SWEEP_WORKFLOW}\n`, stderr: '' });
    assert.ok(!fs.existsSync(file));
    assert.equal(fs.readFileSync(path.join(dir, 'devkit.json'), 'utf8'), config);

    assert.deepEqual(cli(dir, '--check'), { code: 0, stdout: '', stderr: '' });
    assert.deepEqual(cli(dir), { code: 0, stdout: '', stderr: '' });
  }
});

test('the CLI exits 2 with the field errors on an invalid devkit.json, writing and removing nothing', () => {
  const { reviewer, ...noReviewer } = minimal;
  const { dir, file } = onActions({ ...noReviewer, extra: true });
  for (const args of [[dir], [dir, '--check']]) {
    const run = cli(...args);
    assert.equal(run.code, 2);
    assert.match(run.stderr, /reviewer is required/);
    assert.match(run.stderr, /extra is not a known field/);
    assert.equal(run.stdout, '');
  }
  assert.ok(fs.existsSync(file));
});

test('the CLI exits 2 when there is no devkit.json or no project directory', () => {
  assert.equal(cli(project()).code, 2);
  assert.equal(cli().code, 2);
});

// Nothing is written today, so a kit that does write a file is a copy of this one with one added.
function kitThatWrites(relative, contents) {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'devkit-kit-'));
  dirs.push(root);
  for (const file of ['generator/generate.mjs', 'devkit-config.mjs', 'devkit.schema.json']) {
    fs.mkdirSync(path.dirname(path.join(root, file)), { recursive: true });
    fs.copyFileSync(path.join(kitRoot, 'plugin', file), path.join(root, file));
  }
  const generator = path.join(root, 'generator', 'generate.mjs');
  const before = fs.readFileSync(generator, 'utf8');
  const changed = before.replace('  return {};\n', `  return { ${JSON.stringify(relative)}: ${JSON.stringify(contents)} };\n`);
  assert.notEqual(changed, before, 'the generator no longer returns an empty set of files');
  fs.writeFileSync(generator, changed);
  return (...args) => {
    const run = spawnSync(process.execPath, [generator, ...args], { encoding: 'utf8' });
    return { code: run.status, stdout: run.stdout, stderr: run.stderr };
  };
}

test('a kit-owned file is written when missing or edited, the same bytes each time, beside a retired one removed', () => {
  const kit = kitThatWrites('.github/kit-owned.txt', 'from the kit\n');
  const { dir } = onActions();
  const file = path.join(dir, '.github/kit-owned.txt');

  const check = kit(dir, '--check');
  assert.equal(check.code, 1);
  assert.equal(check.stdout, `.github/kit-owned.txt\n${SWEEP_WORKFLOW}\n`);
  assert.ok(!fs.existsSync(file));

  assert.deepEqual(kit(dir), { code: 0, stdout: `wrote .github/kit-owned.txt\nremoved ${SWEEP_WORKFLOW}\n`, stderr: '' });
  assert.equal(fs.readFileSync(file, 'utf8'), 'from the kit\n');
  assert.equal(kit(dir, '--check').code, 0);

  fs.appendFileSync(file, 'a hand edit\n');
  assert.deepEqual(kit(dir, '--check'), { code: 1, stdout: '.github/kit-owned.txt\n', stderr: '1 kit-owned file(s) are behind the kit\n' });
  assert.deepEqual(kit(dir), { code: 0, stdout: 'wrote .github/kit-owned.txt\n', stderr: '' });
  assert.equal(fs.readFileSync(file, 'utf8'), 'from the kit\n');
});
