import { after, test } from 'node:test';
import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { DevkitConfigError } from '../devkit-config.mjs';
import { ACTION, SWEEP_WORKFLOW, generate } from './generate.mjs';

const script = fileURLToPath(new URL('./generate.mjs', import.meta.url));
const kitRoot = fileURLToPath(new URL('../../', import.meta.url));

const minimal = {
  modules: ['process'],
  sweep: { hour: 3 },
  reviewer: { tests: [{ name: 'unit', command: 'npm test' }] },
};

const withDatabase = {
  modules: ['process'],
  sweep: { hour: 5 },
  reviewer: {
    setup: 'npm ci',
    tests: [
      { name: 'unit', command: 'npm test' },
      { name: 'db', command: 'npm run test:db' },
    ],
    env: { TEST_DATABASE_URL: 'postgresql://postgres:postgres@localhost:5432/app_test' },
    services: {
      postgres: {
        image: 'postgres:16',
        env: { POSTGRES_USER: 'postgres', POSTGRES_PASSWORD: 'postgres' },
        ports: ['5432:5432'],
        options: '--health-cmd pg_isready --health-interval 10s --health-timeout 5s --health-retries 5',
      },
    },
  },
};

const servicesBlock = `    services:
      postgres:
        image: postgres:16
        env:
          POSTGRES_PASSWORD: postgres
          POSTGRES_USER: postgres
        ports:
          - '5432:5432'
        options: '--health-cmd pg_isready --health-interval 10s --health-timeout 5s --health-retries 5'
`;

/** The text of each job in a generated workflow, by job id. */
function jobs(workflow) {
  const body = workflow.slice(workflow.indexOf('\njobs:\n') + '\njobs:\n'.length);
  const parts = body.split(/^ {2}(?=[a-z-]+:\n)/m).filter(Boolean);
  return Object.fromEntries(parts.map((part) => [part.slice(0, part.indexOf(':')), part]));
}

const dirs = [];
after(() => dirs.forEach((dir) => fs.rmSync(dir, { recursive: true, force: true })));

function project(config) {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'devkit-generate-'));
  dirs.push(dir);
  if (config !== undefined) fs.writeFileSync(path.join(dir, 'devkit.json'), JSON.stringify(config, null, 2));
  return dir;
}

function cli(...args) {
  const run = spawnSync(process.execPath, [script, ...args], { encoding: 'utf8' });
  return { code: run.status, stdout: run.stdout, stderr: run.stderr };
}

function generateError(config) {
  try {
    generate(config);
  } catch (err) {
    assert.ok(err instanceof DevkitConfigError);
    return err.errors;
  }
  assert.fail('expected generate to refuse this config');
}

test('a minimal config gives the sweep workflow, saying it is generated', () => {
  const files = generate(minimal);
  assert.deepEqual(Object.keys(files), [SWEEP_WORKFLOW]);
  const workflow = files[SWEEP_WORKFLOW];
  const [first, second] = workflow.split('\n');
  assert.match(first, /^# Generated by the devkit generator/);
  assert.match(second, /change devkit\.json/);
  assert.deepEqual(Object.keys(jobs(workflow)), ['sweep', 'landed', 'review-now']);
  assert.equal(workflow.split(`- uses: ${ACTION}\n`).length - 1, 3);
  assert.doesNotMatch(workflow, /^\s+services:/m);
  assert.doesNotMatch(workflow, /repo-env|schedule:|Copy this into/);
  assert.ok(workflow.endsWith('}}\n') && !workflow.endsWith('\n\n'));
});

test('a test database service goes on the jobs that run the tests, and its env stays in devkit.json', () => {
  const byJob = jobs(generate(withDatabase)[SWEEP_WORKFLOW]);
  assert.ok(byJob.sweep.includes(servicesBlock), byJob.sweep);
  assert.ok(byJob['review-now'].includes(servicesBlock), byJob['review-now']);
  assert.doesNotMatch(byJob.landed, /services:/);
  for (const job of Object.values(byJob)) assert.doesNotMatch(job, /repo-env|TEST_DATABASE_URL/);
});

test('a service value YAML would misread is quoted', () => {
  const config = structuredClone(withDatabase);
  config.reviewer.services.postgres.env = { ON: 'yes', POSTGRES_PASSWORD: "it's ${{ secrets.PG }}" };
  config.reviewer.services.postgres.ports = [5432];
  const workflow = generate(config)[SWEEP_WORKFLOW];
  assert.match(workflow, /^ {10}'ON': 'yes'$/m);
  assert.match(workflow, /^ {10}POSTGRES_PASSWORD: 'it''s \$\{\{ secrets\.PG \}\}'$/m);
  assert.match(workflow, /^ {10}- 5432$/m);
});

test('an unknown field is refused, naming it', () => {
  const config = { ...minimal, reviewer: { ...minimal.reviewer, servics: {} } };
  assert.deepEqual(generateError(config), ['reviewer.servics is not a known field']);
});

test('a missing field is refused, naming it', () => {
  const { sweep, ...config } = minimal;
  assert.deepEqual(generateError(config), ['sweep is required']);
});

test('generating twice gives identical output, whatever order devkit.json lists things in', () => {
  const reordered = JSON.parse(JSON.stringify(withDatabase));
  const postgres = reordered.reviewer.services.postgres;
  reordered.reviewer.services = {
    postgres: { options: postgres.options, ports: postgres.ports, image: postgres.image, env: { POSTGRES_PASSWORD: 'postgres', POSTGRES_USER: 'postgres' } },
  };
  assert.deepEqual(generate(withDatabase), generate(withDatabase));
  assert.deepEqual(generate(reordered), generate(withDatabase));
});

test("the kit's own devkit.json generates", () => {
  const config = JSON.parse(fs.readFileSync(path.join(kitRoot, 'devkit.json'), 'utf8'));
  assert.deepEqual(Object.keys(generate(config)), [SWEEP_WORKFLOW]);
});

test('the CLI writes every kit-owned file, the same bytes each time', () => {
  const dir = project(withDatabase);
  const file = path.join(dir, SWEEP_WORKFLOW);
  assert.equal(cli(dir).code, 0);
  const first = fs.readFileSync(file);
  assert.deepEqual(first, Buffer.from(generate(withDatabase)[SWEEP_WORKFLOW]));
  fs.rmSync(file);
  assert.equal(cli(dir).code, 0);
  assert.deepEqual(fs.readFileSync(file), first);
});

test('--check exits 0 on a level project and writes nothing', () => {
  const dir = project(minimal);
  assert.equal(cli(dir).code, 0);
  const run = cli(dir, '--check');
  assert.equal(run.code, 0);
  assert.equal(run.stdout, '');
});

test('--check exits 1 naming each file that drifted or is missing, and writes nothing', () => {
  const dir = project(minimal);
  const file = path.join(dir, SWEEP_WORKFLOW);
  assert.equal(cli(dir).code, 0);
  fs.appendFileSync(file, '# a hand edit\n');
  const edited = fs.readFileSync(file, 'utf8');

  const drifted = cli(dir, '--check');
  assert.equal(drifted.code, 1);
  assert.equal(drifted.stdout, `${SWEEP_WORKFLOW}\n`);
  assert.equal(fs.readFileSync(file, 'utf8'), edited);

  fs.rmSync(file);
  const missing = cli(dir, '--check');
  assert.equal(missing.code, 1);
  assert.equal(missing.stdout, `${SWEEP_WORKFLOW}\n`);
  assert.ok(!fs.existsSync(file));
});

test('the CLI exits 2 with the field errors on an invalid devkit.json, writing nothing', () => {
  const { sweep, ...noSweep } = minimal;
  const dir = project({ ...noSweep, extra: true });
  for (const args of [[dir], [dir, '--check']]) {
    const run = cli(...args);
    assert.equal(run.code, 2);
    assert.match(run.stderr, /sweep is required/);
    assert.match(run.stderr, /extra is not a known field/);
  }
  assert.ok(!fs.existsSync(path.join(dir, '.github')));
});

test('the CLI exits 2 when there is no devkit.json or no project directory', () => {
  assert.equal(cli(project()).code, 2);
  assert.equal(cli().code, 2);
});
